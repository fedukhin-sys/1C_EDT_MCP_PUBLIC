package ru.fedukhin.edt.mcp.tools.testrun.internal;

/**
 * Constant BSL text fragments used by {@link TestRunnerInstaller} to scaffold
 * the runner modules and the ПриНачалеРаботыСистемы handler. Kept as constants
 * (not generated) so that regressions like Stage 7 {@code String.replace("",X)}
 * cannot affect them.
 */
public final class BslRunnerTemplates {

    private BslRunnerTemplates() {}

    public static String clientModuleBody(String serverModuleName) {
        return ""
            + "#Область ПрограммныйИнтерфейс\r\n\r\n"
            + "// Точка входа: проверяет ПараметрЗапуска, если префикс наш —\r\n"
            + "// запускает серверный раннер, пишет результат в файл и завершает работу.\r\n"
            + "Процедура ВыполнитьЕсли7bПараметр() Экспорт\r\n"
            + "\tПрефикс = \"EDT_MCP_TESTS=\";\r\n"
            + "\tПарам = ПараметрЗапуска;\r\n"
            + "\tЕсли НЕ СтрНачинаетсяС(Парам, Префикс) Тогда\r\n"
            + "\t\tВозврат;\r\n"
            + "\tКонецЕсли;\r\n"
            + "\tЗакодированныйСелектор = Сред(Парам, СтрДлина(Префикс) + 1);\r\n"
            + "\tСелектор = РазобратьСелектор(ЗакодированныйСелектор);\r\n"
            + "\tРезультат = " + serverModuleName + ".ВыполнитьТесты(Селектор);\r\n"
            + "\tЗаписатьРезультат(Результат, Селектор.ResultFile);\r\n"
            + "\tЗавершитьРаботуСистемы(Ложь);\r\n"
            + "КонецПроцедуры\r\n\r\n"
            + "Функция РазобратьСелектор(Строка)\r\n"
            + "\tРезультат = Новый Структура(\"Mode, ResultFile, ModuleFqn, MethodName\", \"\", \"\", \"\", \"\");\r\n"
            + "\tДля Каждого Пара Из СтрРазделить(Строка, \";\", Ложь) Цикл\r\n"
            + "\t\tПозиция = СтрНайти(Пара, \"=\");\r\n"
            + "\t\tЕсли Позиция = 0 Тогда Продолжить; КонецЕсли;\r\n"
            + "\t\tКлюч = Лев(Пара, Позиция - 1);\r\n"
            + "\t\tЗначение = Сред(Пара, Позиция + 1);\r\n"
            + "\t\tЕсли Ключ = \"mode\" Тогда Результат.Mode = Значение;\r\n"
            + "\t\tИначеЕсли Ключ = \"rf\" Тогда Результат.ResultFile = РаскодироватьБазу64(Значение);\r\n"
            + "\t\tИначеЕсли Ключ = \"mod\" Тогда Результат.ModuleFqn = Значение;\r\n"
            + "\t\tИначеЕсли Ключ = \"mtd\" Тогда Результат.MethodName = Значение;\r\n"
            + "\t\tКонецЕсли;\r\n"
            + "\tКонецЦикла;\r\n"
            + "\tВозврат Результат;\r\n"
            + "КонецФункции\r\n\r\n"
            + "Функция РаскодироватьБазу64(Строка)\r\n"
            + "\tДанные = Base64Значение(Строка);\r\n"
            + "\tЧтение = Новый ЧтениеТекста(Данные.ОткрытьПотокДляЧтения(), КодировкаТекста.UTF8);\r\n"
            + "\tТекст = Чтение.Прочитать();\r\n"
            + "\tЧтение.Закрыть();\r\n"
            + "\tВозврат Текст;\r\n"
            + "КонецФункции\r\n\r\n"
            + "Процедура ЗаписатьРезультат(Структура, Путь)\r\n"
            + "\tЗапись = Новый ЗаписьJSON;\r\n"
            + "\tЗапись.УстановитьСтроку();\r\n"
            + "\tЗаписатьJSON(Запись, Структура);\r\n"
            + "\tТекст = Запись.Закрыть();\r\n"
            + "\tФайл = Новый ТекстовыйДокумент;\r\n"
            + "\tФайл.УстановитьТекст(Текст);\r\n"
            + "\tФайл.Записать(Путь, КодировкаТекста.UTF8);\r\n"
            + "КонецПроцедуры\r\n\r\n"
            + "#КонецОбласти\r\n";
    }

    public static String serverModuleBody() {
        return ""
            + "#Область ПрограммныйИнтерфейс\r\n\r\n"
            + "// Выполняет тесты согласно селектору, возвращает структуру результата.\r\n"
            + "Функция ВыполнитьТесты(Селектор) Экспорт\r\n"
            + "\tРезультаты = Новый Массив;\r\n"
            + "\tТесты = СобратьТесты(Селектор);\r\n"
            + "\tStartT = ТекущаяУниверсальнаяДатаВМиллисекундах();\r\n"
            + "\tДля Каждого Тест Из Тесты Цикл\r\n"
            + "\t\tT0 = ТекущаяУниверсальнаяДатаВМиллисекундах();\r\n"
            + "\t\tПопытка\r\n"
            + "\t\t\t// Выполнить — операторная форма для вызова процедуры; Вычислить — функция и не может стоять оператором.\r\n"
            + "\t\t\tВыполнить(Тест.Module + \".\" + Тест.Name + \"()\");\r\n"
            + "\t\t\tСтатус = \"passed\";\r\n"
            + "\t\t\tСообщение = Неопределено;\r\n"
            + "\t\tИсключение\r\n"
            + "\t\t\tСтатус = \"failed\";\r\n"
            + "\t\t\tСообщение = ПодробноеПредставлениеОшибки(ИнформацияОбОшибке());\r\n"
            + "\t\tКонецПопытки;\r\n"
            + "\t\tРезультаты.Добавить(Новый Структура(\r\n"
            + "\t\t\t\"module, name, status, durationMs, message\",\r\n"
            + "\t\t\tТест.Module, Тест.Name, Статус,\r\n"
            + "\t\t\tТекущаяУниверсальнаяДатаВМиллисекундах() - T0,\r\n"
            + "\t\t\tСообщение));\r\n"
            + "\tКонецЦикла;\r\n"
            + "\tСчётчики = ПодсчётСтатусов(Результаты);\r\n"
            + "\tВозврат Новый Структура(\r\n"
            + "\t\t\"passed, failed, durationMs, tests\",\r\n"
            + "\t\tСчётчики.Passed, Счётчики.Failed,\r\n"
            + "\t\tТекущаяУниверсальнаяДатаВМиллисекундах() - StartT,\r\n"
            + "\t\tРезультаты);\r\n"
            + "КонецФункции\r\n\r\n"
            + "Функция СобратьТесты(Селектор)\r\n"
            + "\tРезультат = Новый Массив;\r\n"
            + "\tЕсли Селектор.Mode = \"MTD\" Тогда\r\n"
            + "\t\t// Снимаем префикс \"CommonModule.\" — для Выполнить нужно голое имя модуля.\r\n"
            + "\t\t// \"CommonModule.X.Method()\" — это синтаксис MD-ссылки, а не вызов.\r\n"
            + "\t\tИмяМодуля = ИзвлечьИмяМодуля(Селектор.ModuleFqn);\r\n"
            + "\t\tРезультат.Добавить(Новый Структура(\"Module, Name\", ИмяМодуля, Селектор.MethodName));\r\n"
            + "\tКонецЕсли;\r\n"
            + "\t// MOD и ALL — будут перечислять методы динамически в будущей итерации;\r\n"
            + "\t// для Phase 6 живого smoke начинаем с MTD и явно переданных methodFqn-списков.\r\n"
            + "\tВозврат Результат;\r\n"
            + "КонецФункции\r\n\r\n"
            + "Функция ИзвлечьИмяМодуля(Fqn)\r\n"
            + "\tПрефикс = \"CommonModule.\";\r\n"
            + "\tЕсли СтрНачинаетсяС(Fqn, Префикс) Тогда\r\n"
            + "\t\tВозврат Сред(Fqn, СтрДлина(Префикс) + 1);\r\n"
            + "\tКонецЕсли;\r\n"
            + "\tВозврат Fqn;\r\n"
            + "КонецФункции\r\n\r\n"
            + "Функция ПодсчётСтатусов(Массив)\r\n"
            + "\tР = Новый Структура(\"Passed, Failed\", 0, 0);\r\n"
            + "\tДля Каждого Эл Из Массив Цикл\r\n"
            + "\t\tЕсли Эл.status = \"passed\" Тогда Р.Passed = Р.Passed + 1; Иначе Р.Failed = Р.Failed + 1; КонецЕсли;\r\n"
            + "\tКонецЦикла;\r\n"
            + "\tВозврат Р;\r\n"
            + "КонецФункции\r\n\r\n"
            + "#КонецОбласти\r\n";
    }

    public static String handlerProcedureForConfiguration(String clientModuleName) {
        return ""
            + "// Установлено EDT_MCP. Если параметр запуска не наш — handler сразу возвращает управление.\r\n"
            + "Процедура ПриНачалеРаботыСистемы()\r\n"
            + "\t" + clientModuleName + ".ВыполнитьЕсли7bПараметр();\r\n"
            + "КонецПроцедуры\r\n";
    }

    public static String handlerProcedureForExtension(String clientModuleName) {
        return ""
            + "&После(\"ПриНачалеРаботыСистемы\")\r\n"
            + "Процедура EDT_MCP_ПриНачалеРаботыСистемы()\r\n"
            + "\t" + clientModuleName + ".ВыполнитьЕсли7bПараметр();\r\n"
            + "КонецПроцедуры\r\n";
    }
}
